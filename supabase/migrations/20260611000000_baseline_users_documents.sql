-- Baseline Flutter/app schema (pre-spappweb migrations).
-- Required by 20260612000000_create_digital_contracts and later migrations.

CREATE TABLE public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user" text NOT NULL,
  password text,
  vigilado boolean NOT NULL DEFAULT false,
  nota_vigilancia text
);

CREATE UNIQUE INDEX users_user_key ON public.users ("user");

CREATE TABLE public.users_documents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
  document_front_url text NOT NULL,
  document_back_url text NOT NULL,
  selfie_url text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  estado_solicitud text NOT NULL DEFAULT 'pendiente'
    CHECK (estado_solicitud IN ('pendiente', 'aceptada', 'rechazada')),
  hora_actualizacion timestamptz,
  motivo_rechazo text,
  betado boolean NOT NULL DEFAULT false,
  referral_source text
);

CREATE INDEX users_documents_user_id_idx ON public.users_documents(user_id);
CREATE INDEX users_documents_referral_source_idx
  ON public.users_documents(referral_source)
  WHERE referral_source IS NOT NULL;

GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
  ON public.users TO anon, authenticated, service_role;
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES, TRIGGER
  ON public.users_documents TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
